// 1. Hàm Distance
int32_t Distance(int32_t x1, int32_t y1, int32_t x2, int32_t y2 ){
	int32_t dx = abs(x1-x2);
	int32_t dy = abs(y1-y2);
	return (dx*dx + dy*dy);
}

// 2. Hàm Overlab
int32_t Overlab(int32_t x1, int32_t y1, int32_t w1, int32_t h1,
        int32_t x2, int32_t y2, int32_t w2, int32_t h2){
	int32_t right1  = x1 + w1 - 1;
	int32_t top1    = y1 - h1 + 1;
	int32_t right2  = x2 + w2 - 1;
	int32_t top2    = y2 - h2 + 1;

	if (right1 < x2 || x1 > right2 || y1 < top2 || top1 > y2){
	   return 0;
	}
	return 1;
}

